export function getPropertiesByDestination(destinationSlug: string): Property[] {
  return properties.filter((p) => p.destination_slug === destinationSlug);
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return properties.find((p) => p.slug === slug);
}

export function getPropertyByCode(code: string): Property | undefined {
  return properties.find((p) => p.code === code);
}

export function getFeaturedProperties(limit?: number): Property[] {
  const featured = properties.filter((p) => p.featured);
  return limit ? featured.slice(0, limit) : featured;
}

export function getRelatedProperties(property: Property, limit = 3): Property[] {
  return properties
    .filter((p) => p.id !== property.id && p.destination_slug === property.destination_slug)
    .slice(0, limit);
}
